def load_env(path: Path = ENV_PATH) -> dict[str, str]:
    return {key: value for key, value in dotenv_values(path).items() if value is not None}


def _apply_azure_cli_profile() -> None:
    # Per-project Azure CLI profile, so `az account set` in other projects never redirects this demo.
    profile = load_env().get("AZURE_CONFIG_DIR", "").strip()
    if profile:
        os.environ["AZURE_CONFIG_DIR"] = os.path.expandvars(profile)


_apply_azure_cli_profile()


def config() -> dict[str, str]:
    values = load_env(ROOT / ".env.example")
    values.update(load_env())
    values.update({key: value for key, value in os.environ.items() if key in values})
    return values


def require(values: dict[str, str], *keys: str) -> None:
    missing = [key for key in keys if not values.get(key) or "<" in values[key]]
    if missing:
        raise RuntimeError(f"Missing configuration: {', '.join(missing)}. Run scripts\\provision.ps1 first.")


def update_env(values: dict[str, str], path: Path = ENV_PATH) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        text = path.read_text(encoding="utf-8")
    elif path == ENV_PATH and (ROOT / ".env.example").exists():
        text = (ROOT / ".env.example").read_text(encoding="utf-8")
    else:
        text = "# Generated by the Caldova setup scripts; do not commit.\n"
    replacements = {}
    for key, value in values.items():
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise ValueError(f"Invalid environment key: {key}")
        if any(char in str(value) for char in ("\n", "\r", "\0")):
            raise ValueError(f"Multiline environment value is not supported: {key}")
        escaped = str(value).replace("\\", "\\\\").replace("'", "\\'")
        replacements[key] = f"{key}='{escaped}'"
    lines = []
    seen = set()
    for line in text.splitlines():
        match = re.match(r"^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
        key = match.group(1) if match else None
        if key in replacements:
            if key not in seen:
                lines.append(replacements[key])
                seen.add(key)
        else:
            lines.append(line)
    lines.extend(value for key, value in replacements.items() if key not in seen)
    staged = path.with_name(path.name + ".write")
    try:
        staged.write_text("\n".join(lines) + "\n", encoding="utf-8")
        staged.replace(path)
    finally:
        staged.unlink(missing_ok=True)


def az(*args: str, check: bool = True) -> subprocess.CompletedProcess:
    executable = shutil.which("az")
    if not executable:
        raise RuntimeError("Azure CLI is required; run az login first.")
    result = subprocess.run(
        [executable, *args, "--only-show-errors"], cwd=ROOT, capture_output=True, text=True,
        encoding="utf-8", errors="replace", check=False,
    )
    if check and result.returncode:
        raise RuntimeError(result.stderr.strip() or f"Azure CLI failed: {args[0]}")
    return result


def ensure_subscription_enabled(values: dict[str, str]) -> None:
    require(values, "AZURE_SUBSCRIPTION_ID")
    subscription = values["AZURE_SUBSCRIPTION_ID"]
    active = json.loads(az("account", "show", "--output", "json").stdout)
    if active.get("id") != subscription or (
        values.get("AZURE_TENANT_ID") and active.get("tenantId") != values["AZURE_TENANT_ID"]
    ):
        raise RuntimeError(
            f"Azure CLI is on subscription {active.get('id')} (tenant {active.get('tenantId')}), "
            f"but this demo uses {subscription}. Set AZURE_CONFIG_DIR in .env to this project's "
            "Azure CLI profile, or run: az account set --subscription " + subscription
        )
    result = az(
        "rest", "--method", "get", "--url",
        f"https://management.azure.com/subscriptions/{subscription}?api-version=2022-12-01",
        "--output", "json",
    )
    state = json.loads(result.stdout).get("state")
    if str(state).lower() != "enabled":
        raise RuntimeError(
            f"Subscription {subscription} is {state}, not Enabled. No writes attempted. "
            "Re-enable the subscription before deploying."
        )


def make_project(values: dict[str, str], credential):
    from azure.ai.projects import AIProjectClient

    require(values, "FOUNDRY_PROJECT_ENDPOINT")
    return AIProjectClient(
        endpoint=values["FOUNDRY_PROJECT_ENDPOINT"].rstrip("/"),
        credential=credential, allow_preview=True,
    )


def pin_endpoint(project, agent_name: str, version: str, *, incoming_a2a: bool = False, card=None):
    from azure.ai.projects.models import (
        A2AProtocolConfiguration, AgentEndpointConfig, FixedRatioVersionSelectionRule,
        ProtocolConfiguration, ResponsesProtocolConfiguration, VersionSelector,
    )

    protocols = ProtocolConfiguration(responses=ResponsesProtocolConfiguration())
    if incoming_a2a:
        protocols.a2a = A2AProtocolConfiguration()
    kwargs = {}
    if card is not None:
        kwargs["agent_card"] = card
    return project.agents.update_details(
        agent_name=agent_name,
        agent_endpoint=AgentEndpointConfig(
            version_selector=VersionSelector(version_selection_rules=[
                FixedRatioVersionSelectionRule(agent_version=str(version), traffic_percentage=100),
            ]),
            protocol_configuration=protocols,
        ),
        **kwargs,
    )


def agent_principal(project, agent_name: str, version: str, timeout: int = 120) -> str:
    deadline = time.monotonic() + timeout
    while True:
        details = project.agents.get_version(agent_name=agent_name, agent_version=str(version))
        identity = details.instance_identity
        if identity and identity.principal_id:
            return identity.principal_id
        identity = project.agents.get(agent_name=agent_name).instance_identity
        if identity and identity.principal_id:
            return identity.principal_id
        if time.monotonic() >= deadline:
            raise TimeoutError(f"No instance_identity.principal_id for {agent_name} after {timeout}s.")
        time.sleep(5)


def assign_role(principal: str, role: str, scope: str, subscription: str, *, attempts: int = 6) -> None:
    assignment_name = str(uuid.uuid5(uuid.NAMESPACE_URL, f"{scope.lower()}|{principal}|{role}"))
    for attempt in range(attempts):
        result = az(
            "role", "assignment", "create", "--subscription", subscription,
            "--name", assignment_name, "--assignee-object-id", principal,
            "--assignee-principal-type", "ServicePrincipal", "--role", role,
            "--scope", scope, "--output", "none", check=False,
        )
        if not result.returncode or "RoleAssignmentExists" in result.stderr:
            return
        if attempt + 1 == attempts or not any(
            marker in result.stderr for marker in ("PrincipalNotFound", "TooManyRequests", "Conflict")
        ):
            raise RuntimeError(f"Role assignment failed at {scope}: {result.stderr.strip()}")
        time.sleep(10)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("operation", choices=["read", "update", "delete-agents"])
    args = parser.parse_args()
    if args.operation == "read":
        print(json.dumps(load_env()))
    elif args.operation == "update":
        update_env(json.load(sys.stdin))
    else:
        from azure.identity import DefaultAzureCredential

        values = config()
        ensure_subscription_enabled(values)
        with DefaultAzureCredential(process_timeout=60) as credential, make_project(values, credential) as project:
            for name in (values["COORDINATOR_AGENT_NAME"], values["ANALYST_AGENT_NAME"]):
                try:
                    project.agents.delete(agent_name=name, force=True)
                    print(f"Deleted {name}.")
                except Exception as exc:
                    print(f"Agent cleanup skipped for {name}: {exc}", file=sys.stderr)


if __name__ == "__main__":
    main()
